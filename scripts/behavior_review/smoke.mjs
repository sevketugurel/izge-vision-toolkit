import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const url=process.argv[2], output=process.argv[3];
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:1100},acceptDownloads:true});
const page=await context.newPage();
let errors=[];page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',d=>d.accept());
await page.goto(url+'?test_fixture=1');
await page.waitForFunction(()=>document.getElementById('selected').textContent.includes('model skoru'));
assert.equal(await page.evaluate(()=>records.length),0);
await page.locator('#reviewer').fill('automated software fixture');
await page.locator('#posture').selectOption('unknown');
await page.locator('#head_visibility').selectOption('partial');
await page.locator('#body_visibility').selectOption('partial');
await page.locator('#accept').click();
assert.equal(await page.evaluate(()=>records[0].origin),'manual');
assert.equal(await page.evaluate(()=>records[0].test_fixture),true);
await page.locator('#next').click();
await page.waitForFunction(()=>document.getElementById('position').textContent.startsWith('2/'));
await page.locator('#unknown').click();await page.locator('#skip').click();await page.locator('#reject').click();
await page.locator('#goto-full').click();
await page.waitForFunction(()=>document.getElementById('position').textContent.includes('TAM KARE INSTANCE'));
await page.locator('#add').click();
await page.locator('#mode').selectOption('polygon');
const rect=await page.locator('#canvas').boundingBox();
const click=async(x,y)=>page.mouse.click(rect.x+x*rect.width/2560,rect.y+y*rect.height/1440);
await click(100,100);await click(200,100);await click(200,220);await click(100,220);
await page.locator('#polygon').click();await page.locator('#maskbox').click();await page.locator('#correct').click();
assert.equal(await page.evaluate(()=>records.at(-1).action),'add_instance');
assert.deepEqual(await page.evaluate(()=>records.at(-1).mask_rle.size),[1440,2560]);
await page.locator('#mode').selectOption('erase');
await click(150,150);await page.locator('#correct').click();
assert.ok(await page.evaluate(()=>records.at(-1).corrections.mask)>0);
const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();
const download=await downloadPromise;await download.saveAs(output+'/fixture-review.json');
const exported=JSON.parse(fs.readFileSync(output+'/fixture-review.json','utf8'));
assert.equal(exported.events.length,6);assert.ok(exported.events.every(e=>e.test_fixture&&!e.gold&&!e.training_allowed));
const page2=await context.newPage();await page2.goto(url+'?test_fixture=1');
await page2.waitForFunction(()=>document.getElementById('selected').textContent.includes('model skoru'));
await page2.locator('#resume').setInputFiles(output+'/fixture-review.json');
await page2.waitForFunction(()=>records.length===6);
await page2.locator('#reviewer').fill('automated software fixture');await page2.locator('#skip').click();
assert.equal(await page2.evaluate(()=>records.length),7);
assert.deepEqual(await page2.evaluate(()=>records.slice(0,6)),exported.events);
await page2.screenshot({path:output+'/review-ui.png',fullPage:true});
assert.deepEqual(errors,[]);
fs.writeFileSync(output+'/result.json',JSON.stringify({status:'passed',browser:'isolated headless Playwright Chromium',fixture_only:true,human_labels_produced:0,checks:['load creates zero records','accept/unknown/skip/reject','polygon mask creation','mask erasure','add missed instance','original mask shape','download','resume preserves old events','new event appended'],console_errors:errors},null,2));
await browser.close();console.log('Headless review interaction passed; fixtures are not human labels');
