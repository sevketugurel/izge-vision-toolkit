import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const url=process.argv[2], output=process.argv[3];
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:1100},acceptDownloads:true});
const page=await context.newPage();let errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
await page.goto(url+'?test_fixture=1');
await page.waitForFunction(()=>document.getElementById('selected').textContent.includes('model skoru'));
assert.equal(await page.evaluate(()=>items.length),6);
assert.equal(await page.evaluate(()=>records.length),0);
assert.deepEqual(await page.evaluate(()=>data.queue.crops.map(c=>c.light)),['day','night','day','night','day','night']);
assert.equal(await page.locator('#goto-full').isVisible(),false);
assert.equal(await page.locator('#objects button').count(),1);
await page.screenshot({path:output+'/first-six-page.png',fullPage:true});
await page.locator('#reviewer').fill('automated fixture - not human label');
await page.locator('#posture').selectOption('unknown');
await page.locator('#head_visibility').selectOption('partial');
await page.locator('#body_visibility').selectOption('partial');
await page.locator('#mode').selectOption('bbox');
const rect=await page.locator('#canvas').boundingBox();
await page.mouse.move(rect.x+100*rect.width/2560,rect.y+100*rect.height/1440);
await page.mouse.down();
await page.mouse.move(rect.x+400*rect.width/2560,rect.y+400*rect.height/1440);
await page.mouse.up();
assert.ok((await page.locator('#crop-preview').getAttribute('src')).startsWith('data:image/png'));
await page.locator('#correct').click();
assert.equal(await page.evaluate(()=>records[0].action),'correct');
for(let i=1;i<6;i++){
  await page.locator('#next').click();
  await page.waitForFunction(n=>document.getElementById('position').textContent.startsWith(n+'/'),i+1);
  await page.waitForFunction(()=>selected!==null);
  await page.locator(i%2?'#unknown':'#skip').click();
}
const promise=page.waitForEvent('download');await page.locator('#export').click();
await (await promise).saveAs(output+'/fixture-review.json');
const r=JSON.parse(fs.readFileSync(output+'/fixture-review.json','utf8'));
assert.equal(r.events.length,6);assert.ok(r.events.every(e=>e.test_fixture&&!e.gold&&!e.training_allowed));
assert.deepEqual(errors,[]);
fs.writeFileSync(output+'/result.json',JSON.stringify({status:'passed',human_labels:0,fixture_only:true,checks:['six only','balanced day/night','single target per crop','load creates zero events','corrected crop preview','six fixture actions','versioned download'],errors},null,2));
await browser.close();console.log('First-six UI passed; fixtures are not human labels');
